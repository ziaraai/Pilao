#!/usr/bin/env bash
# Called by .github/workflows/deploy.yml on the server, in /opt/pilao:
#   deploy.sh <api image> <web image>     (secrets from GitHub on stdin, KEY=value lines)
# 1. secrets.env: created once with generated passwords, then the GitHub secrets merged in;
# 2. the new images pulled, the database migrated, the new version started;
# 3. it must answer (API ready, web page) or the previous version is put back.
set -euo pipefail
cd "$(dirname "$0")"
API_IMAGE=$1
WEB_IMAGE=$2
for tool in docker curl openssl; do
  command -v "$tool" >/dev/null || { echo "::error::$tool is missing on the server (docs/14, server setup)"; exit 1; }
done
docker compose version >/dev/null 2>&1 \
  || { echo "::error::« docker compose » is missing on the server (docs/14, server setup)"; exit 1; }

# ---- secrets (server only, never in git) --------------------------------------------
umask 077
if [ ! -f secrets.env ]; then
  pw=$(openssl rand -hex 24)
  {
    echo "# Generated by deploy.sh on $(date -u +%F). Back it up: without it the database"
    echo "# password and the download-link key are lost."
    echo "POSTGRES_PASSWORD=$pw"
    echo "DATABASE_URL=postgresql+psycopg://pilao:$pw@postgres:5432/pilao"
    echo "APP_SECRET_KEY=$(openssl rand -hex 32)"
  } > secrets.env
  echo "secrets.env created (new database password and signing key)"
fi
incoming=$(mktemp)
trap 'rm -f "$incoming"' EXIT
cat > "$incoming"  # GitHub secrets, one KEY=value per line; empty values are skipped
while IFS= read -r line; do
  key=${line%%=*}
  value=${line#*=}
  case "$key" in OPENROUTER_API_KEY|SMTP_PASSWORD) ;; *) continue ;; esac
  [ -n "$value" ] || continue
  grep -v "^$key=" secrets.env > secrets.env.new || true
  printf '%s=%s\n' "$key" "$value" >> secrets.env.new
  mv secrets.env.new secrets.env
done < "$incoming"
chmod 600 secrets.env

# ---- the new version ----------------------------------------------------------------
[ -f release.env ] && cp release.env release.previous.env
printf 'PILAO_API_IMAGE=%s\nPILAO_WEB_IMAGE=%s\n' "$API_IMAGE" "$WEB_IMAGE" > release.env

answers() {  # up to 3 minutes: the first start of the API loads LibreOffice and the AI layer
  for _ in $(seq 1 "${PILAO_HEALTH_TRIES:-60}"); do
    if curl -fs -o /dev/null http://127.0.0.1:8100/ready \
      && curl -fs -o /dev/null http://127.0.0.1:3100/connexion; then
      return 0
    fi
    sleep 3
  done
  return 1
}

[ -n "${PILAO_SKIP_PULL:-}" ] || ./pilao.sh pull --quiet api web
./pilao.sh up -d postgres redis clamav
./pilao.sh run --rm migrate  # additive migrations: the running version keeps working
./pilao.sh up -d --remove-orphans api worker scheduler web
if answers; then
  echo "deployed: $API_IMAGE"
  docker image prune -f >/dev/null || true
  exit 0
fi

echo "::error::the new version does not answer: putting the previous one back"
./pilao.sh logs --tail 80 api web || true
if [ -f release.previous.env ]; then
  cp release.previous.env release.env
  ./pilao.sh up -d api worker scheduler web
  if answers; then echo "previous version running again"; fi
fi
exit 1
